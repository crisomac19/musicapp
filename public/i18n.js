  // English
  US: "en", GB: "en", CA: "en", AU: "en", NZ: "en", IE: "en", JM: "en", TT: "en", BS: "en", BZ: "en",
  ZA: "en", NG: "en", GH: "en", KE: "en", PH: "en", SG: "en", IN: "en",
  // Spanish
